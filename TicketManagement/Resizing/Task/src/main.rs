fn main() {
    let mut v = Vec::with_capacity(2);
    v.push(1);
    v.push(2); // досягнуто максимальної capacity
    assert_eq!(v.capacity(), 2);

    v.push(3); // capacity перевищено, потрібно змінити розмір

    // Чи здогадаєтеся, якою буде нова capacity?
    // Зверніть увагу: стандартна бібліотека не дає жодних гарантій щодо
    // алгоритму зміни розміру вектора, тож у майбутньому це може змінитися.
    assert_eq!(v.capacity(), 4);
}
