// TODO: у кожному з модулів цього crate (одиниці компіляції Rust) на вас чекає робота!
mod description;
mod status;
mod title;

// Поширений pattern (типовий прийом) у Rust — розбити код на кілька (приватних) модулів,
// а потім реекспортувати публічні частини цих модулів у crate root (кореневому модулі).
//
// Так внутрішня структура crate прихована від його користувачів, а ви водночас
// можете організувати свій код як завгодно.
pub use description::TicketDescription;
pub use status::Status;
pub use title::TicketTitle;

#[derive(Debug, PartialEq, Clone)]
// Нам більше не потрібно робити поля приватними!
// Оскільки кожне поле інкапсулює власну логіку валідації, немає ризику, що
// користувач `Ticket` змінить поля так, що це порушить
// інваріанти struct.
//
// Але будьте обережні: якби у вас були інваріанти, що охоплюють кілька полів,
// вам довелося б подбати про те, щоб ці інваріанти й далі виконувалися, і знову
// зробити поля приватними.
pub struct Ticket {
    pub title: TicketTitle,
    pub description: TicketDescription,
    pub status: Status,
}
